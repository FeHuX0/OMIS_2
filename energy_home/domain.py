@dataclass
class ДомКвартира:
    """Класс Дом / Квартира (4.1, стр. 13): адрес, +получитьОбщееПотребление(): Double, 1..* -> Комната."""

    адрес: str
    комнаты: list[Комната] = field(default_factory=list)
    тип: str = "квартира"
    базовое_потребление_сегодня_квтч: float = 0.0
    базовая_мощность_квт: float = 0.0

    def получитьОбщееПотребление(self) -> float:
        """Рассчитать суммарное потребление дома по показаниям всех комнат и приборов (метод 4.1)."""
        сумма = self.базовое_потребление_сегодня_квтч
        for комната in self.комнаты:
            for прибор in комната.приборы:
                if прибор.устройство_учета is not None:
                    сумма += sum(п.значение for п in прибор.устройство_учета.показания)
        return round(сумма, 2)

    def текущая_мощность_квт(self) -> float:
        """Текущая суммарная мощность всех включённых приборов дома в кВт."""
        сумма_вт = 0.0
        for комната in self.комнаты:
            for прибор in комната.приборы:
                сумма_вт += прибор.текущая_мощность_вт()
        if сумма_вт == 0.0 and self.базовая_мощность_квт > 0.0:
            return round(self.базовая_мощность_квт, 2)
        return round(self.базовая_мощность_квт + (сумма_вт / 1000.0), 1)

    def добавить_комнату(self, комната: Комната) -> None:
        self.комнаты.append(комната)


