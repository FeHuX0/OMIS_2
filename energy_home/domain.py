from __future__ import annotations

import hashlib
import hmac
import secrets
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from enum import Enum
from typing import Any, Optional

try:
    from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

    LOCAL_TZ: Any = ZoneInfo("Europe/Minsk")
except (ImportError, ZoneInfoNotFoundError):
    LOCAL_TZ = timezone(timedelta(hours=3), name="Europe/Minsk")


class ОшибкаДомена(Exception):
    """Базовое исключение предметной области."""


class ОшибкаВалидации(ОшибкаДомена):
    """Ошибка некорректных входных данных или нарушения инварианта."""


class ОшибкаДоступа(ОшибкаДомена):
    """Ошибка аутентификации или проверки прав (RBAC)."""


def хешировать_пароль(пароль: str) -> str:
    """Хеширование пароля PBKDF2-SHA256 (260 000 итераций)."""
    if not isinstance(пароль, str) or len(пароль) < 6:
        raise ОшибкаВалидации("Пароль должен содержать не менее 6 символов.")
    соль = secrets.token_bytes(16)
    хеш = hashlib.pbkdf2_hmac("sha256", пароль.encode("utf-8"), соль, 260_000, dklen=32)
    return f"pbkdf2_sha256$260000${соль.hex()}${хеш.hex()}"


def проверить_пароль(пароль: str, сохраненный_хеш: str) -> bool:
    """Сравнение пароля с PBKDF2-SHA256 хешем за постоянное время."""
    части = (сохраненный_хеш or "").split("$")
    if len(части) != 4 or части[0] != "pbkdf2_sha256":
        return False
    _, итерации_стр, соль_hex, ожидаемый_hex = части
    try:
        итерации = int(итерации_стр)
        соль = bytes.fromhex(соль_hex)
        ожидаемый = bytes.fromhex(ожидаемый_hex)
    except ValueError:
        return False
    фактический = hashlib.pbkdf2_hmac("sha256", (пароль or "").encode("utf-8"), соль, итерации, dklen=32)
    return hmac.compare_digest(фактический, ожидаемый)


