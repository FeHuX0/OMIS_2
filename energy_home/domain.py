@dataclass
class Аномалия:
    """Класс Аномалия (диаграмма 4.2.3, стр. 15; ER-3/ER-5): тип, величина, время, +описать(): String."""

    тип: str
    величина: float
    время: datetime
    место: str = "линии кухни"
    пользовательская_подпись_времени: Optional[str] = None

    def описать(self) -> str:
        знак = "+" if self.величина >= 0 else ""
        время_стр = self.пользовательская_подпись_времени or self.время.strftime("%d.%m.%Y %H:%M")
        return f"{self.тип} на {self.место} ({знак}{int(round(self.величина))}%)\n{время_стр}."


